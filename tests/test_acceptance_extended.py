"""Pruebas adicionales precisas para aceptación y no para cubrir automáticamente las 50 HU."""
from test_ui import sync_playwright,mount,browser_args
checks=[]
def ck(s,x):
    assert x,s
    checks.append(s)
    print('PASS',s,flush=True)
with sync_playwright() as p:
    browser=p.chromium.launch(**browser_args())
    page=browser.new_page(viewport={'width':1280,'height':900})
    page.set_default_timeout(5000)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    mount(page)
    page.locator('#app-tabs [data-tab="evaluar"]').click()
    page.locator('#space-sample').select_option('aula')
    page.locator('#space-form button[type=submit]').click()
    for a in ['No','No','Sí']:
        page.locator('#eval-form input[value="'+a+'"]').check()
        page.locator('#eval-form button[type=submit]').click()
    page.locator('#app-tabs [data-tab="riesgos"]').click()
    page.locator('#risk-type').select_option('Vidrio')
    page.locator('#risk-level').select_option('Precaución')
    page.locator('#risk-desc').fill('Ventana cerca de ejemplo')
    page.locator('#risk-form button[type=submit]').click()
    page.locator('#app-tabs [data-tab="zonas"]').click()
    page.locator('#map-filter').select_option('riesgos')
    ck('HU-045 S2 filtro Riesgos',page.locator('.map-marker.risk').count()==1 and page.locator('.map-marker.zone').count()==0 and page.locator('.map-route').count()==0)
    page.locator('#map-filter').select_option('zonas')
    ck('HU-045 S2 filtro Zonas',page.locator('.map-marker.zone').count()==1 and page.locator('.map-marker.risk').count()==0)
    page.locator('#app-tabs [data-tab="checklist"]').click()
    page.locator('#new-check').fill('Revisar salida señalizada de ejemplo')
    page.locator('#add-check-form button[type=submit]').click()
    ck('HU-038 S2 añadir item personalizado', 'Revisar salida señalizada de ejemplo' in page.locator('#app-content').inner_text() and page.locator('[data-check]').count()==4)
    page.locator('[data-check="mochila"]').check()
    ck('HU-038 S1 progreso del checklist', '25 % completado' in page.locator('#app-content').inner_text())
    page.locator('#app-tabs [data-tab="practica"]').click()
    page.locator('[data-scenario="lights"]').last.click()
    page.locator('[data-action="answer-sim"][data-choice="0"]').click()
    ck('HU-037 S2 repetir escenario tras error',page.get_by_role('button',name='Repetir escenario').count()==1 and 'Respuesta por revisar' in page.locator('#app-content').inner_text())
    page.locator('#app-tabs [data-tab="progreso"]').click()
    page.locator('#history-filter').select_option('Evaluación')
    ck('HU-040 S2 filtro evaluaciones',page.locator('.history-table tbody tr').count()==1 and 'Evaluación' in page.locator('.history-table').inner_text() and 'Simulacro' not in page.locator('.history-table').inner_text())
    page.locator('#history-filter').select_option('Simulacro')
    ck('HU-040 S2 filtro simulacros',page.locator('.history-table tbody tr').count()==1 and 'Simulacro' in page.locator('.history-table').inner_text() and 'Evaluación' not in page.locator('.history-table').inner_text())
    ck('JS runtime — pruebas extendidas sin excepciones',len(errors)==0)
    browser.close()
print('TOTAL',len(checks),'comprobaciones adicionales aprobadas')
